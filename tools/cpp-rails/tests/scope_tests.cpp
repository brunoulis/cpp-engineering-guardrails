#include "cpp_rails.hpp"
#include "quality.hpp"

#include <algorithm>
#include <chrono>
#include <fstream>
#include <iostream>
#include <stdexcept>

using namespace cpprails;
#define REQUIRE(x) do { if (!(x)) throw std::runtime_error(#x); } while (false)
namespace {
struct Fixture {
    fs::path root=fs::temp_directory_path()/("cpp-rails-scope-"+std::to_string(std::chrono::steady_clock::now().time_since_epoch().count()));
    Fixture(){fs::create_directories(root);}
    ~Fixture(){std::error_code ec;fs::remove_all(root,ec);}
    void put(const fs::path& path,const std::string& text){fs::create_directories((root/path).parent_path());std::ofstream out(root/path);out<<text;out.close();REQUIRE(out.good());}
};
void generated_sources_do_not_pollute_selected_quality(){
    Fixture f;
    f.put("app.cpp","int value = 1;\n");
    f.put("binding.g.cpp","int generated_value = 2;\nint* ptr = new int;\n");
    f.put("binding.g.h","int* other = new int;\n");
    f.put("banner.cpp","// GENERATED CODE - DO NOT MODIFY BY HAND\nint* value = new int;\n");
    f.put("block.hpp","/*\n * Generated by schema compiler. DO NOT EDIT.\n */\nint* value = new int;\n");
    f.put("ffi_bindings.h","// AUTO GENERATED FILE, DO NOT EDIT.\nint ffi_value=3;\n");
    const auto s=scan(f.root);
    REQUIRE(s.files.size()==1);REQUIRE(s.files_excluded==5);REQUIRE(s.skipped==0);
    REQUIRE(s.findings.empty());
    const auto q=quality_score(f.root,s.files);
    REQUIRE(q.files==1);REQUIRE(q.code_lines==1);
}
void fragments_are_scanned_and_resolved_by_topology(){
    Fixture f;
    f.put("main.cpp","#include \"body.inc\"\n");
    f.put("body.inc","#include \"impl.inl\"\nint* ptr = new int;\n");
    f.put("impl.inl","int* another = new int;\n");
    const auto s=scan(f.root);
    REQUIRE(s.files.size()==3);REQUIRE(s.fragments_scanned==2);REQUIRE(s.observed_paths.count("body.inc"));REQUIRE(s.observed_paths.count("impl.inl"));
    REQUIRE(s.findings.size()==2);
    Report r;report_topology(f.root,s.files,{},r);
    REQUIRE(std::any_of(r.notes.begin(),r.notes.end(),[](const auto& note){return note.find("3 source/header nodes, 2 include edges")!=std::string::npos;}));
    REQUIRE(std::any_of(r.notes.begin(),r.notes.end(),[](const auto& note){return note.find("Highly included: impl.inl fan-in=1")!=std::string::npos;}));
}
void authored_generated_mentions_are_kept(){
    Fixture f;
    f.put("generated_helpers.cpp","const char* banner = \"GENERATED CODE - DO NOT EDIT\";\nint value = 1;\n");
    f.put("normal.cpp","// Helpers for generated bindings.\nint value = 2;\n");
    f.put("late.cpp","int first = 1;\n// GENERATED CODE - DO NOT EDIT\nint second = 2;\n");
    const auto s=scan(f.root);REQUIRE(s.files.size()==3);
}
void generated_opt_in_restores_files_but_not_dependencies(){
    Fixture f;f.put("generated/binding.g.cpp","// GENERATED CODE\nint value=1;\n");
    f.put("nested/generated/fragment.inc","int other=2;\n");
    f.put("vendor/dependency.cpp","int dependency=3;\n");
    const auto normal=scan(f.root);REQUIRE(normal.files.empty());REQUIRE(normal.files_excluded==2);REQUIRE(normal.directories_excluded==1);
    ScanPolicy policy;policy.include_generated=true;
    const auto included=scan(f.root,{},"general",false,policy);
    REQUIRE(included.files.size()==2);REQUIRE(included.fragments_scanned==1);REQUIRE(included.files_excluded==0);REQUIRE(included.directories_excluded==1);
}
void repeatable_exclusions_handle_windows_separators_and_keep_scope_consistent(){
    Fixture f;f.put("src/keep.cpp","int keep=1;\n");f.put("src/drop.cpp","int* ptr=new int;\n");
    f.put("space dir/nested/drop.cpp","int* ptr=new int;\n");
    const auto options=parse_options(false,{"audit","--root",utf8_bytes(f.root.u8string()),"--score","--exclude","space dir\\*","--exclude","src/drop.cpp"});
    Report r;REQUIRE(dispatch(options,r)==0);REQUIRE(r.files_scanned==1);REQUIRE(r.files_excluded==1);REQUIRE(r.directories_excluded==1);REQUIRE(r.files_skipped==0);REQUIRE(r.findings.empty());
    REQUIRE(r.sections.front().json.find("\"code_lines\":1")!=std::string::npos);
    REQUIRE(json(r).find("explicit --exclude")!=std::string::npos);REQUIRE(markdown(r).find("Source exclusions")!=std::string::npos);
    Report escaped;escaped.exclusions.push_back({"dir/quote\"and\nnewline.cpp","reason\nnext","file"});
    REQUIRE(json(escaped).find("quote\\\"and\\nnewline.cpp")!=std::string::npos);
}
void excluded_baseline_findings_stay_unobserved(){
    Fixture f;f.put("binding.g.cpp","int* ptr=new int;\n");f.put("drop.cpp","int* other=new int;\n");
    Options before;before.root=f.root;before.scan_policy.include_generated=true;
    Report baseline;REQUIRE(dispatch(before,baseline)==0);REQUIRE(baseline.findings.size()==2);write_baseline(f.root/"baseline.txt",baseline);
    Options after;after.root=f.root;after.baseline="baseline.txt";after.scan_policy.excludes={"drop.cpp"};
    Report compared;REQUIRE(dispatch(after,compared)==0);REQUIRE(compared.delta.resolved.empty());REQUIRE(compared.delta.unobserved==2);
}
void deleted_generated_baseline_paths_stay_unobserved(){
    Fixture f;f.put("binding.g.cpp","int* ptr=new int;\n");
    Options before;before.root=f.root;before.scan_policy.include_generated=true;
    Report baseline;REQUIRE(dispatch(before,baseline)==0);write_baseline(f.root/"baseline.txt",baseline);fs::remove(f.root/"binding.g.cpp");
    Options after;after.root=f.root;after.baseline="baseline.txt";
    Report compared;REQUIRE(dispatch(after,compared)==0);REQUIRE(compared.delta.resolved.empty());REQUIRE(compared.delta.unobserved==1);
}
void compdb_cli_preserves_evaluated_export_configuration(){
    const auto o=parse_options(false,{"compdb","--msvc-project","project with spaces.vcxproj","--config","Release","--platform","Win32","--include-generated"});
    REQUIRE(o.action=="compdb");REQUIRE(o.msvc_project==fs::path("project with spaces.vcxproj"));REQUIRE(o.config=="Release");REQUIRE(o.platform=="Win32");REQUIRE(o.scan_policy.include_generated);
    REQUIRE(parse_options(false,{"compdb"}).platform=="x64");
}
void deleted_banner_generated_scope_is_not_called_resolved(){
    Fixture f;f.put("banner.cpp","// AUTO GENERATED FILE - DO NOT EDIT\nint* value=new int;\n");
    Options before;before.root=f.root;before.scan_policy.include_generated=true;
    Report baseline;REQUIRE(dispatch(before,baseline)==0);REQUIRE(baseline.findings.size()==1);write_baseline(f.root/"baseline.txt",baseline);
    fs::remove(f.root/"banner.cpp");
    Options after;after.root=f.root;after.baseline="baseline.txt";
    Report compared;REQUIRE(dispatch(after,compared)==0);REQUIRE(compared.delta.resolved.empty());REQUIRE(compared.delta.unobserved==1);
    after.scan_policy.include_generated=true;
    Report same_scope;REQUIRE(dispatch(after,same_scope)==0);REQUIRE(same_scope.delta.resolved.size()==1);
    f.put("legacy.txt","# cpp-rails baseline v1\nold\tbanner.cpp\tCPP-RAW-ALLOC\n");
    after.baseline="legacy.txt";
    Report legacy;REQUIRE(dispatch(after,legacy)==0);REQUIRE(legacy.delta.resolved.empty());REQUIRE(legacy.delta.unobserved==1);
}
}
int main(){
    int failures=0;
    const auto test=[&](const char* name,auto run){try{run();std::cout<<"PASS "<<name<<'\n';}catch(const std::exception& e){++failures;std::cerr<<"FAIL "<<name<<": "<<e.what()<<'\n';}};
    test("generated quality scope",generated_sources_do_not_pollute_selected_quality);
    test("fragment discovery and topology",fragments_are_scanned_and_resolved_by_topology);
    test("authored generated mentions",authored_generated_mentions_are_kept);
    test("generated opt-in and dependency boundary",generated_opt_in_restores_files_but_not_dependencies);
    test("explicit exclusions and reporting",repeatable_exclusions_handle_windows_separators_and_keep_scope_consistent);
    test("baseline scope shrink",excluded_baseline_findings_stay_unobserved);
    test("deleted generated baseline path",deleted_generated_baseline_paths_stay_unobserved);
    test("deleted banner-generated baseline scope",deleted_banner_generated_scope_is_not_called_resolved);
    test("MSBuild export CLI options",compdb_cli_preserves_evaluated_export_configuration);
    return failures?1:0;
}
